#!/usr/bin/env bash
set -uo pipefail
# ============================================================================
# template-sync.test.sh — AC-4-3 sync wiring + R3 allowlist cleanup (Phase 22 Plan 04)
# ============================================================================
REPO="$(cd "$(dirname "$0")/.." && pwd)"
SYNC="$REPO/sync-project.sh"
INIT="$REPO/forge-init.sh"
ALLOW="$REPO/.forge/sync-allowlist.json"

PASS=0; FAIL=0
ok()  { printf '  \033[32mPASS\033[0m %s\n' "$1"; PASS=$((PASS+1)); }
bad() { printf '  \033[31mFAIL\033[0m %s\n' "$1"; FAIL=$((FAIL+1)); }

echo "── AC-4-3 derived allowlist (R3 cleanup) ──"
# the consumer allowlist is the forge-extract-DERIVED artifact, not hand-authored
jq -e '.["$schema_note"] | test("GENERATED by forge-extract")' "$ALLOW" >/dev/null 2>&1 \
    && ok "allowlist is the GENERATED/derived artifact (not hand-authored)" || bad "allowlist is not the derived artifact"
# excluded skills absent from the consumer allowlist skills[]
for x in project-bootstrap _deprecated_project-bootstrap project-sync project-template-sync ghl-architect n8n-node-expert azure-m365-architect; do
    jq -e --arg s "$x" '.skills | index($s) | not' "$ALLOW" >/dev/null 2>&1 && : || bad "excluded skill '$x' LEAKED into allowlist"
done
ok "no excluded/domain skill present in allowlist skills[]"
# no 3-way merge code path (grep for actual merge mechanisms, not the explanatory prose)
grep -qE 'diff3|merge-base|git[[:space:]]+merge-file' "$SYNC" && bad "sync has a 3-way-merge code path (should be deferred to 22.1)" || ok "no 3-way-merge code path (overwrite-on-apply)"

echo "── AC-4-3 sync dry-run + apply ──"
# stand up a consumer with a complete fixture
WB="$(mktemp -d)"; WORKSPACE_DIR="$WB" bash "$INIT" "SyncSeed" syncseed "a" >/dev/null 2>&1 || true
SCOPE=(".claude/rules" ".claude/skills" ".claude/hooks" ".githooks" "scripts/forge" "CLAUDE.md" ".claude/gate.config.json" ".claude/forge.config.json" ".carl/manifest")
SP=(); for s in "${SCOPE[@]}"; do [ -e "$WB/SyncSeed/$s" ] && SP+=("$WB/SyncSeed/$s"); done
ANS="$(mktemp)"; grep -rhoE '\{\{[A-Za-z0-9_][A-Za-z0-9_-]*\}\}' "${SP[@]}" 2>/dev/null | sort -u | sed 's/^{{//;s/}}$//' \
    | jq -R . | jq -s 'map({key:.,value:"x"})|from_entries' > "$ANS"
rm -rf "$WB"
WP="$(mktemp -d)"; WORKSPACE_DIR="$WP" bash "$INIT" --answers "$ANS" "SyncProj" syncdom "a,b" >/dev/null 2>&1
PROJ="$WP/SyncProj"

# force a MODIFIED on an allowlisted rule
echo "# local drift" >> "$PROJ/.claude/rules/verification-discipline.md"
OUT="$(bash "$SYNC" "$PROJ" 2>&1)"
printf '%s' "$OUT" | grep -q '\[MODIFIED\].*verification-discipline.md' && ok "modified allowlisted rule shows [MODIFIED]" || bad "drifted rule not detected"
# domain skills NEVER appear in the sync output
printf '%s' "$OUT" | grep -qiE 'ghl-architect|n8n-(node|workflow|code)|azure-m365' && bad "a domain skill appeared in sync output" || ok "no domain skill ever appears in sync output"
# CLAUDE.md + configs are SKIP (consumer-owned), never MODIFIED
printf '%s' "$OUT" | grep -qE '\[(NEW|MODIFIED)\].*(CLAUDE\.md|gate\.config\.json|forge\.config\.json|settings\.json)' && bad "a consumer-owned file would be overwritten" || ok "CLAUDE.md + configs + settings ⇒ [SKIP] (never overwritten)"
printf '%s' "$OUT" | grep -q '\[SKIP\]' && ok "protected/consumer-owned files reported [SKIP]" || bad "no [SKIP] reporting"

# apply ⇒ drift resolved + commit-SHA marker written
bash "$SYNC" "$PROJ" --apply >/dev/null 2>&1
grep -q 'local drift' "$PROJ/.claude/rules/verification-discipline.md" && bad "apply did not overwrite the drifted rule" || ok "apply overwrote the drifted rule"
[ -f "$PROJ/.forge/forge-template-version" ] && grep -q 'forge-template-version:' "$PROJ/.forge/forge-template-version" && ok "forge-template-version (commit-SHA) marker written" || bad "drift marker missing"

rm -rf "$WP" "$ANS"
echo ""
echo "── result: ${PASS} passed, ${FAIL} failed ──"
[ "$FAIL" -eq 0 ]
